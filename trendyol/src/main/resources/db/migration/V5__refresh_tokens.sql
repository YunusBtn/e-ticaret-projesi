CREATE TABLE trendyol.refresh_tokens
(

    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL,
    token_hash varchar(64)  not null,
    family_id  varchar(36)  not null,
    expires_at timestamp(6) not null,
    used_at    timestamp(6),
    revoked_at timestamp(6),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    CONSTRAINT refresh_tokens_token_hash_key unique (token_hash),
    CONSTRAINT fk_refresh_tokens_user foreign key (user_id) references trendyol.users (id)
);


create index idx_refresh_tokens_user_id on trendyol.refresh_tokens (user_id);
create index idx_refresh_tokens_family_id on trendyol.refresh_tokens (family_id);