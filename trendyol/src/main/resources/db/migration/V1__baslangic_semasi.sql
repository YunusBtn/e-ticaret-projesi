
CREATE TABLE trendyol.users
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   VARCHAR(255) NOT NULL,
    email      VARCHAR(255) NOT NULL,
    password   VARCHAR(255) NOT NULL,
    role       VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6),
    CONSTRAINT users_username_key UNIQUE (username),
    CONSTRAINT users_email_key UNIQUE (email),
    CONSTRAINT users_role_check CHECK (role IN ('ADMIN', 'USER'))
);

CREATE TABLE trendyol.products
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(255)   NOT NULL,
    description    VARCHAR(1000)  NOT NULL,
    price          NUMERIC(10, 2) NOT NULL,
    stock_quantity INTEGER        NOT NULL,
    version        BIGINT         NOT NULL DEFAULT 0,
    creadet_at     TIMESTAMP(6)
);

CREATE TABLE trendyol.orders
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT         NOT NULL,
    total_price NUMERIC(10, 2) NOT NULL,
    status      VARCHAR(255)   NOT NULL,
    version     BIGINT         NOT NULL DEFAULT 0,
    created_at  TIMESTAMP(6),
    CONSTRAINT orders_status_check
        CHECK (status IN ('PENDING', 'PAID', 'SHIPPED', 'DELIVERED', 'CANCELLED')),
    CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES trendyol.users (id)
);

CREATE TABLE trendyol.order_items
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT         NOT NULL,
    product_id BIGINT         NOT NULL,
    quantity   INTEGER        NOT NULL,
    unit_price NUMERIC(10, 2) NOT NULL,
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES trendyol.orders (id),
    CONSTRAINT fk_order_items_product FOREIGN KEY (product_id) REFERENCES trendyol.products (id)
);

CREATE TABLE trendyol.payments
(
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT         NOT NULL,
    amount   NUMERIC(38, 2) NOT NULL,
    method   VARCHAR(255)   NOT NULL,
    status   VARCHAR(255)   NOT NULL,
    paid_at  TIMESTAMP(6),
    CONSTRAINT payments_order_id_key UNIQUE (order_id),
    CONSTRAINT payments_method_check CHECK (method IN ('CREDIT_CARD', 'BANK_TRANSFER')),
    CONSTRAINT payments_status_check CHECK (status IN ('SUCCESS', 'FAILED', 'PENDING')),
    CONSTRAINT fk_payments_order FOREIGN KEY (order_id) REFERENCES trendyol.orders (id)
);

CREATE TABLE trendyol.notifications
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL,
    message    VARCHAR(500) NOT NULL,
    is_read    BOOLEAN      NOT NULL,
    type       VARCHAR(255) NOT NULL,
    creadet_at TIMESTAMP(6),
    CONSTRAINT notifications_type_check CHECK (type IN (
                                                        'ORDER_CREATED', 'ORDER_UPDATED', 'ORDER_DELETED',
                                                        'PAYMENT_SUCCESS', 'PAYMENT_FAILED', 'ORDER_SHIPPED')),
    CONSTRAINT fk_notifications_user FOREIGN KEY (user_id) REFERENCES trendyol.users (id)
);